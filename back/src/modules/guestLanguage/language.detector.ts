/**
 * Idioma en que está escrito un mensaje, o null si no se puede saber (mensajes cortos o
 * neutros como "ok", "👍" o "20-11-2026"): en ese caso se conserva el que ya tenía el chat.
 */
export function detectLanguage(text: string): GuestLanguage | null {
  const words = text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .split(/[^a-zñ]+/)
    .filter(Boolean);

  let english = 0;
  let spanish = 0;
  for (const word of words) {
    if (ENGLISH_WORDS.has(word)) english++;
    if (SPANISH_WORDS.has(word)) spanish++;
  }

  // Un saludo suelto ("hello", "hola") alcanza si el otro idioma no aparece.
  if (english > spanish && (english >= 2 || spanish === 0))
    return GuestLanguage.EN;
  if (spanish > english && (spanish >= 2 || english === 0))
    return GuestLanguage.ES;
  return null;
}
